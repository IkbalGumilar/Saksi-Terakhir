using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.Rendering;
using UnityEngine.SceneManagement;

/// <summary>Creates vegetation materials, three-level LOD prefabs and native import evidence.</summary>
[InitializeOnLoad]
public static class ModularVegetationImport
{
    const string Folder = "Assets/ModularAsset/Lingkungan/Vegetasi";
    const string Source = "SourceArt/ModularAsset/Vegetation";
    const string ReportName = "/unity-import-verification.json";
    const float SizeTolerance = .025f;
    static readonly float[] LodThresholds = { .45f, .18f, .025f };
    static double nextCheck;
    static bool busy;

    static ModularVegetationImport()
    {
        if (!Application.isBatchMode) EditorApplication.update += CheckPending;
    }

    [Serializable] public class AssetInfo
    {
        public string name, category, description, anchor, fbx;
        public float snap_m;
        public float[] size_blender_m, bounds_min_blender, bounds_max_blender;
        public int lodcount, lod_count;
        public int[] lod_triangle_budgets;
        public float collider_radius_m, collider_height_m;
        public float[] collider_box_blender_m, collider_center_blender_m;
    }
    [Serializable] public class MaterialInfo { public string name, key; public float[] srgb; public float roughness, metallic; }
    [Serializable] public class Placement { public string asset; public float[] position_blender; public float rotation_z; }
    [Serializable] public class Example { public string name; public Placement[] placements; }
    [Serializable] public class Manifest { public AssetInfo[] assets; public MaterialInfo[] materials; public Example[] examples; }
    [Serializable] public class LodResult
    {
        public int level, renderers, meshes, vertices, triangles, triangleBudget;
        public float screenRelativeTransitionHeight;
        public Vector3 boundsMin, boundsMax;
    }
    [Serializable] public class ModelResult
    {
        public string name, category, model, prefab, modelGuid, prefabGuid, colliderType;
        public int renderers, triangles, colliders, meshColliders, missingMaterials;
        public int meshesMissingNormals, meshesMissingPrimaryUv, meshesMissingLightmapUv;
        public int ungroupedRenderers, lodGroupCount, lodCount, animators, animations, skinnedRenderers;
        public Vector3 size, expectedSize, boundsMin, boundsMax, colliderCenter, colliderSize;
        public float sizeDifference, boundsDifference, colliderRadius, colliderHeight;
        public bool positiveScale, allRenderersEnabled, descendingLodTriangles, withinTriangleBudgets;
        public List<LodResult> lods = new List<LodResult>();
    }
    [Serializable] public class ImportMessage { public string asset, severity, message; }
    [Serializable] public class Report
    {
        public string checkedUtc, completedUtc, exportReadyUtc, projectPath, unityVersion;
        public string folder = Folder;
        public int expectedModels, models, prefabs, materialCount;
        public bool pass;
        public List<string> errors = new List<string>();
        public List<ImportMessage> unityMessages = new List<ImportMessage>();
        public List<ModelResult> assets = new List<ModelResult>();
        public List<string> examples = new List<string>();
    }

    static string DiskPath(string relative) { return Path.Combine(Path.GetDirectoryName(Application.dataPath), relative); }
    static Vector3 ToUnity(float[] value) { return new Vector3(value[0], value[2], value[1]); }
    static bool IsVector(float[] value) { return value != null && value.Length == 3 && value.All(v => !float.IsNaN(v) && !float.IsInfinity(v)); }

    static void CheckPending()
    {
        if (busy || EditorApplication.timeSinceStartup < nextCheck || EditorApplication.isCompiling || EditorApplication.isUpdating || EditorApplication.isPlayingOrWillChangePlaymode) return;
        nextCheck = EditorApplication.timeSinceStartup + 5;
        string ready = DiskPath(Source + "/export.ready"), reportPath = DiskPath(Source + ReportName);
        if (!File.Exists(ready) || !File.Exists(DiskPath(Folder + "/manifest.json"))) return;
        if (File.Exists(reportPath) && File.GetLastWriteTimeUtc(reportPath) >= File.GetLastWriteTimeUtc(ready))
        {
            try
            {
                var completed = JsonUtility.FromJson<Report>(File.ReadAllText(reportPath));
                if (completed != null && completed.exportReadyUtc == File.GetLastWriteTimeUtc(ready).ToString("O")) return;
            }
            catch (Exception) { /* An incomplete report is regenerated by the native importer. */ }
        }
        Prepare();
    }

    static bool PositiveScale(Transform transform)
    {
        Vector3 scale = transform.localScale;
        return scale.x > 0 && scale.y > 0 && scale.z > 0 && transform.localToWorldMatrix.determinant > 0;
    }

    static int FindLod(Transform part, Transform root)
    {
        for (Transform t = part; t && t != root; t = t.parent)
            for (int level = 0; level < 3; level++)
                if (string.Equals(t.name, "LOD" + level, StringComparison.Ordinal)) return level;
        return -1;
    }

    static int MeshTriangles(Mesh mesh)
    {
        int triangles = 0;
        for (int sub = 0; sub < mesh.subMeshCount; sub++)
        {
            if (mesh.GetTopology(sub) != MeshTopology.Triangles) throw new Exception("Non-triangle imported submesh: " + mesh.name);
            triangles += (int)mesh.GetIndexCount(sub) / 3;
        }
        return triangles;
    }

    static void ConfigureOpaqueMaterial(Material material, Shader shader, MaterialInfo info)
    {
        material.name = info.name;
        material.shader = shader;
        material.SetColor("_BaseColor", new Color(info.srgb[0], info.srgb[1], info.srgb[2], 1));
        material.SetFloat("_Metallic", info.metallic);
        material.SetFloat("_Smoothness", 1 - info.roughness);
        material.SetFloat("_Surface", 0);
        material.SetFloat("_Blend", 0);
        material.SetFloat("_AlphaClip", 0);
        material.SetFloat("_SrcBlend", (float)BlendMode.One);
        material.SetFloat("_DstBlend", (float)BlendMode.Zero);
        material.SetFloat("_ZWrite", 1);
        material.SetFloat("_Cull", (float)CullMode.Back);
        material.DisableKeyword("_SURFACE_TYPE_TRANSPARENT");
        material.DisableKeyword("_ALPHATEST_ON");
        material.DisableKeyword("_ALPHAPREMULTIPLY_ON");
        material.SetOverrideTag("RenderType", "Opaque");
        material.SetShaderPassEnabled("ShadowCaster", true);
        material.renderQueue = (int)RenderQueue.Geometry;
        material.doubleSidedGI = false;
        material.enableInstancing = true;
    }

    static void AddCentralCollider(GameObject instance, AssetInfo info, ModelResult result)
    {
        if (instance.GetComponentsInChildren<Collider>(true).Length != 0) throw new Exception("Imported source unexpectedly contains a collider");
        bool capsuleSpecified = info.collider_radius_m > 0 || info.collider_height_m > 0;
        bool boxSpecified = info.collider_box_blender_m != null && info.collider_box_blender_m.Length > 0;
        if (capsuleSpecified && boxSpecified) throw new Exception("Both capsule and box collider metadata are present");
        if (info.category == "Pohon")
        {
            if (!capsuleSpecified || info.collider_radius_m <= 0 || info.collider_height_m < info.collider_radius_m * 2)
                throw new Exception("Tree requires a positive trunk capsule with height at least twice its radius");
            var collider = instance.AddComponent<CapsuleCollider>();
            collider.direction = 1;
            collider.center = new Vector3(0, info.collider_height_m * .5f, 0);
            collider.radius = info.collider_radius_m;
            collider.height = info.collider_height_m;
            result.colliderType = "CapsuleCollider";
            result.colliderCenter = collider.center;
            result.colliderRadius = collider.radius;
            result.colliderHeight = collider.height;
        }
        else if (capsuleSpecified) throw new Exception("Trunk capsule metadata is only valid for Pohon assets");
        else if (boxSpecified)
        {
            if (info.category != "Pot" && info.category != "Palem") throw new Exception("Box collider metadata is only valid for pots and potted palms");
            if (!IsVector(info.collider_box_blender_m) || info.collider_box_blender_m.Any(v => v <= 0) || !IsVector(info.collider_center_blender_m))
                throw new Exception("Pot collider requires positive metric dimensions and a finite centre");
            var collider = instance.AddComponent<BoxCollider>();
            collider.size = ToUnity(info.collider_box_blender_m);
            collider.center = ToUnity(info.collider_center_blender_m);
            result.colliderType = "BoxCollider";
            result.colliderCenter = collider.center;
            result.colliderSize = collider.size;
        }
        else result.colliderType = "None";
        result.colliders = instance.GetComponentsInChildren<Collider>(true).Length;
        result.meshColliders = instance.GetComponentsInChildren<MeshCollider>(true).Length;
        if (result.meshColliders != 0 || result.colliders != (capsuleSpecified || boxSpecified ? 1 : 0))
            throw new Exception("Vegetation collider configuration is invalid");
    }

    [MenuItem("Tools/Modular Asset/Prepare Vegetation Assets")]
    public static void Prepare()
    {
        if (busy || EditorApplication.isPlayingOrWillChangePlaymode) return;
        busy = true;
        var report = new Report
        {
            checkedUtc = DateTime.UtcNow.ToString("O"),
            projectPath = Path.GetDirectoryName(Application.dataPath),
            unityVersion = Application.unityVersion
        };
        Scene previousScene = SceneManager.GetActiveScene();
        Scene workScene = default;
        string currentAsset = "Preparation";
        Application.LogCallback capture = (message, stack, type) =>
        {
            if (type != LogType.Error && type != LogType.Exception && type != LogType.Assert && type != LogType.Warning) return;
            report.unityMessages.Add(new ImportMessage { asset = currentAsset, severity = type.ToString(), message = message });
            if (type != LogType.Warning) report.errors.Add(currentAsset + ": Unity " + type + ": " + message);
        };
        Application.logMessageReceived += capture;
        try
        {
            string readyPath = DiskPath(Source + "/export.ready");
            if (!File.Exists(readyPath)) throw new Exception("Blender export is not ready");
            report.exportReadyUtc = File.GetLastWriteTimeUtc(readyPath).ToString("O");
            var manifest = JsonUtility.FromJson<Manifest>(File.ReadAllText(DiskPath(Folder + "/manifest.json")));
            if (manifest == null || manifest.assets == null || manifest.assets.Length == 0) throw new Exception("Asset manifest is empty");
            if (manifest.materials == null || manifest.materials.Length == 0) throw new Exception("Material manifest is empty");
            report.expectedModels = manifest.assets.Length;
            if (manifest.assets.Any(a => string.IsNullOrEmpty(a.fbx) || !a.fbx.StartsWith(Folder + "/Models/", StringComparison.Ordinal) || !File.Exists(DiskPath(a.fbx))))
                throw new Exception("Blender export is incomplete or its model path is outside the vegetation kit");
            if (manifest.assets.GroupBy(a => a.name).Any(g => string.IsNullOrEmpty(g.Key) || g.Count() > 1)) throw new Exception("Asset names are empty or duplicated");
            if (manifest.materials.GroupBy(a => a.name).Any(g => string.IsNullOrEmpty(g.Key) || g.Count() > 1)) throw new Exception("Material names are empty or duplicated");

            // This private scene also works when the user's active scene is untitled and unsaved.
            workScene = EditorSceneManager.NewPreviewScene();
            Directory.CreateDirectory(DiskPath(Folder + "/Materials"));
            Directory.CreateDirectory(DiskPath(Folder + "/Prefabs"));
            foreach (string category in manifest.assets.Select(a => a.category).Distinct())
                Directory.CreateDirectory(DiskPath(Folder + "/Prefabs/" + category));
            AssetDatabase.Refresh(ImportAssetOptions.ForceSynchronousImport);

            Shader shader = Shader.Find("Universal Render Pipeline/Lit");
            if (!shader) throw new Exception("URP Lit shader was not found");
            var materials = new Dictionary<string, Material>();
            foreach (var info in manifest.materials)
            {
                currentAsset = info.name;
                if (info.srgb == null || info.srgb.Length < 3) throw new Exception("Invalid material colour: " + info.name);
                string path = Folder + "/Materials/" + info.name + ".mat";
                var material = AssetDatabase.LoadAssetAtPath<Material>(path);
                if (!material) { material = new Material(shader); AssetDatabase.CreateAsset(material, path); }
                ConfigureOpaqueMaterial(material, shader, info);
                string texturePath = Folder + "/Textures/" + info.name + "_Albedo.png";
                if (File.Exists(DiskPath(texturePath)))
                {
                    var textureImporter = AssetImporter.GetAtPath(texturePath) as TextureImporter;
                    if (!textureImporter) throw new Exception("No texture importer: " + texturePath);
                    textureImporter.wrapMode = TextureWrapMode.Repeat;
                    textureImporter.sRGBTexture = true;
                    textureImporter.maxTextureSize = 1024;
                    textureImporter.mipmapEnabled = true;
                    textureImporter.alphaIsTransparency = false;
                    textureImporter.SaveAndReimport();
                    var texture = AssetDatabase.LoadAssetAtPath<Texture2D>(texturePath);
                    if (!texture) throw new Exception("Texture not loaded: " + texturePath);
                    material.SetTexture("_BaseMap", texture);
                    material.SetColor("_BaseColor", Color.white);
                }
                EditorUtility.SetDirty(material);
                materials.Add(info.name, material);
            }
            report.materialCount = materials.Count;
            var prefabs = new Dictionary<string, GameObject>();
            foreach (var info in manifest.assets)
            {
                currentAsset = info.name;
                GameObject instance = null;
                try
                {
                    if (!IsVector(info.size_blender_m) || !IsVector(info.bounds_min_blender) || !IsVector(info.bounds_max_blender))
                        throw new Exception("Expected metric dimensions or pivot bounds are missing");
                    if ((info.lod_count != 0 ? info.lod_count : info.lodcount) != 3) throw new Exception("Vegetation asset must declare exactly three LODs");
                    var importer = AssetImporter.GetAtPath(info.fbx) as ModelImporter;
                    if (!importer) throw new Exception("No model importer: " + info.fbx);
                    importer.globalScale = 1;
                    importer.useFileScale = true;
                    importer.bakeAxisConversion = true;
                    importer.importCameras = false;
                    importer.importLights = false;
                    importer.importAnimation = false;
                    importer.animationType = ModelImporterAnimationType.None;
                    importer.importBlendShapes = false;
                    importer.importConstraints = false;
                    importer.importVisibility = false;
                    importer.importNormals = ModelImporterNormals.Import;
                    importer.importTangents = ModelImporterTangents.CalculateMikk;
                    importer.materialImportMode = ModelImporterMaterialImportMode.ImportStandard;
                    importer.materialName = ModelImporterMaterialName.BasedOnMaterialName;
                    importer.materialSearch = ModelImporterMaterialSearch.Local;
                    importer.generateSecondaryUV = true;
                    importer.isReadable = false;
                    importer.preserveHierarchy = true;
                    importer.addCollider = false;
                    foreach (var material in materials)
                        importer.AddRemap(new AssetImporter.SourceAssetIdentifier(typeof(Material), material.Key), material.Value);
                    importer.SaveAndReimport();
                    var model = AssetDatabase.LoadAssetAtPath<GameObject>(info.fbx);
                    if (!model) throw new Exception("Model not loaded: " + info.fbx);
                    instance = (GameObject)PrefabUtility.InstantiatePrefab(model, workScene);
                    instance.name = info.name;
                    instance.transform.SetPositionAndRotation(Vector3.zero, Quaternion.identity);
                    foreach (var importedLod in instance.GetComponentsInChildren<LODGroup>(true)) UnityEngine.Object.DestroyImmediate(importedLod);
                    foreach (Transform transform in instance.GetComponentsInChildren<Transform>(true)) transform.gameObject.SetActive(true);
                    var renderers = instance.GetComponentsInChildren<MeshRenderer>(true);
                    var result = new ModelResult
                    {
                        name = info.name, category = info.category, model = info.fbx, modelGuid = AssetDatabase.AssetPathToGUID(info.fbx),
                        renderers = renderers.Length, positiveScale = true, allRenderersEnabled = true,
                        expectedSize = ToUnity(info.size_blender_m), descendingLodTriangles = true, withinTriangleBudgets = true
                    };
                    var lodRenderers = new[] { new List<Renderer>(), new List<Renderer>(), new List<Renderer>() };
                    var lodBounds = new Bounds[3];
                    var lodMeshes = new[] { new HashSet<Mesh>(), new HashSet<Mesh>(), new HashSet<Mesh>() };
                    for (int level = 0; level < 3; level++)
                        result.lods.Add(new LodResult
                        {
                            level = level, screenRelativeTransitionHeight = LodThresholds[level],
                            triangleBudget = info.lod_triangle_budgets != null && info.lod_triangle_budgets.Length == 3
                                ? info.lod_triangle_budgets[level] : (info.category == "Pohon" ? 65000 : 40000)
                        });
                    Bounds bounds = new Bounds();
                    bool first = true;
                    foreach (var renderer in renderers)
                    {
                        // Exported Blender LOD1/2 visibility must not become a permanently disabled Unity renderer.
                        renderer.enabled = true;
                        result.allRenderersEnabled &= renderer.enabled;
                        if (first) { bounds = renderer.bounds; first = false; } else bounds.Encapsulate(renderer.bounds);
                        foreach (var material in renderer.sharedMaterials)
                            if (!material || !AssetDatabase.GetAssetPath(material).StartsWith(Folder + "/Materials/", StringComparison.Ordinal)
                                || material.shader != shader || material.GetFloat("_Surface") != 0 || material.GetFloat("_Cull") != (float)CullMode.Back)
                                result.missingMaterials++;
                        var filter = renderer.GetComponent<MeshFilter>();
                        if (!filter || !filter.sharedMesh) throw new Exception("Renderer has no mesh: " + renderer.name);
                        Mesh mesh = filter.sharedMesh;
                        if (renderer.sharedMaterials.Length != mesh.subMeshCount) throw new Exception("Material slots differ from mesh submeshes: " + renderer.name);
                        if (!mesh.HasVertexAttribute(VertexAttribute.Normal)) result.meshesMissingNormals++;
                        if (!mesh.HasVertexAttribute(VertexAttribute.TexCoord0)) result.meshesMissingPrimaryUv++;
                        if (!mesh.HasVertexAttribute(VertexAttribute.TexCoord1)) result.meshesMissingLightmapUv++;
                        int triangles = MeshTriangles(mesh);
                        result.triangles += triangles;
                        int level = FindLod(renderer.transform, instance.transform);
                        if (level < 0) { result.ungroupedRenderers++; continue; }
                        var lod = result.lods[level];
                        if (lodRenderers[level].Count == 0) lodBounds[level] = renderer.bounds;
                        else lodBounds[level].Encapsulate(renderer.bounds);
                        lodRenderers[level].Add(renderer);
                        lodMeshes[level].Add(mesh);
                        lod.triangles += triangles;
                        lod.vertices += mesh.vertexCount;
                    }
                    if (result.ungroupedRenderers != 0) throw new Exception("Renderers exist outside LOD0, LOD1 or LOD2");
                    for (int level = 0; level < 3; level++)
                    {
                        var lod = result.lods[level];
                        lod.renderers = lodRenderers[level].Count;
                        lod.meshes = lodMeshes[level].Count;
                        lod.boundsMin = lodBounds[level].min;
                        lod.boundsMax = lodBounds[level].max;
                        if (lod.renderers == 0 || lod.triangles == 0) throw new Exception("LOD" + level + " is empty");
                        if (lod.triangleBudget <= 0 || lod.triangles > lod.triangleBudget) result.withinTriangleBudgets = false;
                        if (level > 0 && lod.triangles >= result.lods[level - 1].triangles) result.descendingLodTriangles = false;
                    }
                    var group = instance.AddComponent<LODGroup>();
                    group.fadeMode = LODFadeMode.None;
                    group.animateCrossFading = false;
                    group.SetLODs(Enumerable.Range(0, 3).Select(level => new LOD(LodThresholds[level], lodRenderers[level].ToArray())).ToArray());
                    group.RecalculateBounds();
                    result.lodCount = group.lodCount;
                    result.lodGroupCount = instance.GetComponentsInChildren<LODGroup>(true).Length;
                    AddCentralCollider(instance, info, result);
                    result.animators = instance.GetComponentsInChildren<Animator>(true).Length;
                    result.animations = instance.GetComponentsInChildren<Animation>(true).Length;
                    result.skinnedRenderers = instance.GetComponentsInChildren<SkinnedMeshRenderer>(true).Length;
                    foreach (Transform transform in instance.GetComponentsInChildren<Transform>(true)) if (!PositiveScale(transform)) result.positiveScale = false;
                    result.size = bounds.size;
                    result.boundsMin = bounds.min;
                    result.boundsMax = bounds.max;
                    result.sizeDifference = (result.expectedSize - result.size).magnitude;
                    result.boundsDifference = Mathf.Max((ToUnity(info.bounds_min_blender) - bounds.min).magnitude, (ToUnity(info.bounds_max_blender) - bounds.max).magnitude);
                    if (result.boundsDifference > SizeTolerance) report.errors.Add(info.name + ": imported pivot/orientation bounds differ by " + result.boundsDifference.ToString("F5") + " m");
                    if (result.sizeDifference > SizeTolerance) report.errors.Add(info.name + ": imported metric size differs by " + result.sizeDifference.ToString("F5") + " m");
                    if (result.missingMaterials > 0 || !result.positiveScale || result.renderers == 0 || result.triangles == 0)
                        report.errors.Add(info.name + ": material, scale, renderer or geometry issue");
                    if (result.meshesMissingNormals > 0 || result.meshesMissingPrimaryUv > 0 || result.meshesMissingLightmapUv > 0)
                        report.errors.Add(info.name + ": imported mesh is missing normals, primary UVs or generated lightmap UVs");
                    if (result.lodGroupCount != 1 || result.lodCount != 3 || !result.descendingLodTriangles || !result.withinTriangleBudgets)
                        report.errors.Add(info.name + ": LOD grouping, descending geometry or triangle budget issue");
                    if (result.animators > 0 || result.animations > 0 || result.skinnedRenderers > 0)
                        report.errors.Add(info.name + ": static vegetation unexpectedly imported animation or skinned geometry");
                    result.prefab = Folder + "/Prefabs/" + info.category + "/" + info.name + ".prefab";
                    var prefab = PrefabUtility.SaveAsPrefabAsset(instance, result.prefab);
                    if (!prefab) throw new Exception("Prefab was not saved: " + result.prefab);
                    result.prefabGuid = AssetDatabase.AssetPathToGUID(result.prefab);
                    prefabs.Add(info.name, prefab);
                    string[] labels = { "ModularAsset", "Vegetasi", info.category };
                    AssetDatabase.SetLabels(model, labels);
                    AssetDatabase.SetLabels(prefab, labels);
                    report.assets.Add(result);
                    report.models++;
                    report.prefabs++;
                }
                catch (Exception exception) { report.errors.Add(info.name + ": " + exception); }
                finally { if (instance) UnityEngine.Object.DestroyImmediate(instance); }
            }
            if (manifest.examples != null)
                foreach (var example in manifest.examples)
                {
                    currentAsset = example.name;
                    var root = new GameObject(example.name);
                    SceneManager.MoveGameObjectToScene(root, workScene);
                    try
                    {
                        foreach (var placement in example.placements ?? new Placement[0])
                        {
                            if (!prefabs.TryGetValue(placement.asset, out var prefab)) { report.errors.Add(example.name + ": missing example asset " + placement.asset); continue; }
                            if (!IsVector(placement.position_blender)) { report.errors.Add(example.name + ": invalid position for " + placement.asset); continue; }
                            var child = (GameObject)PrefabUtility.InstantiatePrefab(prefab, workScene);
                            child.transform.SetParent(root.transform, false);
                            child.transform.localPosition = ToUnity(placement.position_blender);
                            child.transform.localRotation = Quaternion.Euler(0, -placement.rotation_z * Mathf.Rad2Deg, 0);
                        }
                        string examplePath = Folder + "/Prefabs/" + example.name + ".prefab";
                        var examplePrefab = PrefabUtility.SaveAsPrefabAsset(root, examplePath);
                        if (!examplePrefab) throw new Exception("Example prefab was not saved: " + examplePath);
                        AssetDatabase.SetLabels(examplePrefab, new[] { "ModularAsset", "Vegetasi", "Example" });
                        report.examples.Add(examplePath);
                    }
                    catch (Exception exception) { report.errors.Add(example.name + ": " + exception); }
                    finally { UnityEngine.Object.DestroyImmediate(root); }
                }
            currentAsset = "Saving";
            AssetDatabase.SaveAssets();
            if (report.exportReadyUtc != File.GetLastWriteTimeUtc(readyPath).ToString("O")) report.errors.Add("Blender export changed during native import; run the importer again");
            report.pass = report.errors.Count == 0 && report.models == manifest.assets.Length && report.prefabs == manifest.assets.Length;
        }
        catch (Exception exception) { report.errors.Add(exception.ToString()); report.pass = false; }
        finally
        {
            Application.logMessageReceived -= capture;
            if (previousScene.IsValid() && previousScene.isLoaded) SceneManager.SetActiveScene(previousScene);
            if (workScene.IsValid() && workScene.isLoaded) EditorSceneManager.ClosePreviewScene(workScene);
            busy = false;
            report.completedUtc = DateTime.UtcNow.ToString("O");
            Directory.CreateDirectory(DiskPath(Source));
            File.WriteAllText(DiskPath(Source + ReportName), JsonUtility.ToJson(report, true));
            if (report.pass) Debug.Log("ModularAsset Vegetasi: " + report.models + " models, " + report.prefabs + " prefabs, three LODs each; pass=True");
            else Debug.LogError("ModularAsset Vegetasi import failed: " + report.errors.Count + " errors; see " + Source + ReportName);
        }
    }
}
